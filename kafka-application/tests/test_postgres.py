"""Real PostgreSQL checks; opt in with a dedicated STOCK_VIEW_TEST_DSN.

Only *_test or test_* database names are accepted. Every test creates and drops
its own random schema in that test database; development tables are never used.
These tests do not start Kafka and do not claim a full TV3/TV4 integration.
"""

from concurrent.futures import ThreadPoolExecutor
import os
from threading import Barrier
import unittest
from uuid import uuid4

import psycopg
from psycopg import sql
from psycopg.conninfo import conninfo_to_dict
from psycopg.rows import dict_row

from common.event_schema import stock_updated
from services.stock_view.database import init_db, process_event


def versioned_event(version, stock, event_id=None):
    result = stock_updated("P01", stock)
    result["data"]["version"] = version
    if event_id is not None:
        result["event_id"] = event_id
    return result


TEST_DSN = os.getenv("STOCK_VIEW_TEST_DSN")


@unittest.skipUnless(TEST_DSN, "STOCK_VIEW_TEST_DSN is not set; real PostgreSQL not verified")
class PostgreSQLTestCase(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        try:
            settings = conninfo_to_dict(TEST_DSN)
        except psycopg.Error:
            raise ValueError("STOCK_VIEW_TEST_DSN is not valid libpq connection information") from None
        name = settings.get("dbname", "")
        forbidden = {
            "inventory_db", "stock_view_db", "postgres", "template0", "template1",
            os.getenv("INVENTORY_DB_NAME", "inventory_db"),
            os.getenv("STOCK_VIEW_DB_NAME", "stock_view_db"),
        }
        if name in forbidden or not (name.endswith("_test") or name.startswith("test_")):
            raise ValueError("STOCK_VIEW_TEST_DSN must explicitly name a separate *_test or test_* database")
        cls.database_name = name

    def setUp(self):
        self.schema = f"tv4_test_{uuid4().hex}"
        self.admin = self.connect_test_database()
        self.addCleanup(self.admin.close)
        actual = self.admin.execute("SELECT current_database() AS name").fetchone()["name"]
        self.assertEqual(actual, self.database_name)
        self.admin.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(self.schema)))
        self.addCleanup(self.drop_schema)
        self.admin.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(self.schema)))
        init_db(self.admin)

    def drop_schema(self):
        # The exact identifier was generated by this test, never taken from a user path.
        self.admin.execute(sql.SQL("DROP SCHEMA {} CASCADE").format(sql.Identifier(self.schema)))

    def connection(self):
        connection = self.connect_test_database()
        connection.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(self.schema)))
        return connection

    @staticmethod
    def connect_test_database():
        try:
            return psycopg.connect(TEST_DSN, autocommit=True, row_factory=dict_row)
        except psycopg.Error:
            # Do not echo a DSN or a malformed DSN fragment containing credentials.
            raise RuntimeError("Cannot connect to the dedicated STOCK_VIEW_TEST_DSN database") from None

    def stock(self):
        return self.admin.execute("SELECT stock_after, version FROM stock_levels WHERE product_id = %s", ("P01",)).fetchone()

    def processed_count(self):
        return self.admin.execute("SELECT count(*) AS count FROM processed_events").fetchone()["count"]


class PostgreSQLStockViewTests(PostgreSQLTestCase):
    def test_schema_initialization_is_repeatable(self):
        process_event(self.admin, versioned_event(0, 10))
        init_db(self.admin)
        self.assertEqual(self.stock(), {"stock_after": 10, "version": 0})

    def test_parameterized_ids_and_strict_version_upsert(self):
        seed = versioned_event(2, 8, event_id="event-'quoted';--")
        self.assertTrue(process_event(self.admin, seed)["updated"])
        self.assertTrue(process_event(self.admin, seed)["duplicate"])
        self.assertFalse(process_event(self.admin, versioned_event(2, 100))["updated"])
        self.assertFalse(process_event(self.admin, versioned_event(1, 99))["updated"])
        self.assertEqual(self.stock(), {"stock_after": 8, "version": 2})
        self.assertEqual(self.processed_count(), 3)
        self.assertTrue(process_event(self.admin, versioned_event(3, 7))["updated"])
        self.assertEqual(self.stock(), {"stock_after": 7, "version": 3})

    def test_actual_sql_error_rolls_back_processed_event_and_projection(self):
        process_event(self.admin, versioned_event(1, 10, "seed"))
        # Force an actual PostgreSQL error inside the second write, after the
        # processed_events INSERT. No simulated SQL engine is used here.
        self.admin.execute("ALTER TABLE stock_levels ADD CONSTRAINT test_stock_limit CHECK (stock_after <= 10)")
        failing = versioned_event(2, 11, "must-rollback")
        with self.assertRaises(psycopg.errors.CheckViolation):
            process_event(self.admin, failing)
        self.assertEqual(self.stock(), {"stock_after": 10, "version": 1})
        self.assertEqual(self.processed_count(), 1)
        failing["data"]["stock_after"] = 9
        self.assertTrue(process_event(self.admin, failing)["updated"])
        self.assertEqual(self.stock(), {"stock_after": 9, "version": 2})

    def test_commit_failure_rolls_back_both_tables(self):
        process_event(self.admin, versioned_event(1, 10, "seed-p01"))
        second = versioned_event(1, 9, "seed-p02")
        second["data"]["product_id"] = "P02"
        process_event(self.admin, second)
        self.admin.execute(
            "ALTER TABLE stock_levels ADD CONSTRAINT test_unique_stock "
            "UNIQUE (stock_after) DEFERRABLE INITIALLY DEFERRED"
        )
        # Both INSERTs/UPDATEs succeed; the unique violation happens only at COMMIT.
        with self.assertRaises(psycopg.errors.UniqueViolation):
            process_event(self.admin, versioned_event(2, 9, "commit-must-rollback"))
        self.assertEqual(self.stock(), {"stock_after": 10, "version": 1})
        self.assertEqual(self.processed_count(), 2)

    def test_concurrent_duplicate_event_is_applied_once(self):
        barrier = Barrier(4)
        payload = versioned_event(1, 9, "concurrent-duplicate")

        def worker(_):
            with self.connection() as conn:
                barrier.wait(timeout=15)
                return process_event(conn, payload)

        with ThreadPoolExecutor(max_workers=4) as pool:
            results = list(pool.map(worker, range(4)))
        self.assertEqual(sum(result["updated"] for result in results), 1)
        self.assertEqual(sum(result["duplicate"] for result in results), 3)
        self.assertEqual(self.processed_count(), 1)

    def test_concurrent_versions_leave_the_highest_version(self):
        barrier = Barrier(4)

        def worker(version):
            with self.connection() as conn:
                barrier.wait(timeout=15)
                return process_event(conn, versioned_event(version, 100 - version))

        with ThreadPoolExecutor(max_workers=4) as pool:
            list(pool.map(worker, (3, 1, 4, 2)))
        self.assertEqual(self.stock(), {"stock_after": 96, "version": 4})
        self.assertEqual(self.processed_count(), 4)

    def test_legacy_tv3_stock_event_is_a_visible_contract_failure(self):
        with self.assertRaisesRegex(ValueError, "TV3 must publish"):
            process_event(self.admin, stock_updated("P01", 10))
        self.assertIsNone(self.stock())
        self.assertEqual(self.processed_count(), 0)


class PostgreSQLComponentTests(PostgreSQLTestCase):
    """Native TV3 code + TV4 Payment + projection; Kafka is replaced by ack fake.

    Two schemas in the dedicated TEST database isolate the test components.
    Actual services must still run with separate databases and separate accounts.
    """

    def setUp(self):
        super().setUp()
        from services.inventory.database import init_db as init_inventory

        self.inventory_schema = f"tv4_inventory_test_{uuid4().hex}"
        self.admin.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(self.inventory_schema)))
        self.addCleanup(self.drop_inventory_schema)
        self.inventory = self.inventory_connection()
        self.addCleanup(self.inventory.close)
        init_inventory(self.inventory)

    def drop_inventory_schema(self):
        self.admin.execute(sql.SQL("DROP SCHEMA {} CASCADE").format(sql.Identifier(self.inventory_schema)))

    def inventory_connection(self):
        connection = self.connect_test_database()
        connection.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(self.inventory_schema)))
        return connection

    def failed_payment_flow(self):
        from services.inventory.consumer import process_event as inventory_process
        from services.inventory.database import seed_product
        from services.order.producer import create_order
        from services.payment.consumer import process_event as payment_process
        from services.payment.settings import PaymentSettings

        seed_product(self.inventory, "P01", 10)
        order = create_order("P01", 3, order_id="component-failure")
        reserved = inventory_process(self.inventory, order, "orders.created")
        self.assertTrue(reserved["result"]["success"])
        inventory_result = self.inventory.execute(
            "SELECT payload FROM outbox_events WHERE topic = %s AND message_key = %s",
            ("inventory.results", "component-failure"),
        ).fetchone()["payload"]
        payment = payment_process(AcknowledgingProducer(), inventory_result, PaymentSettings(mode="failure"))
        self.assertFalse(payment["payment_event"]["data"]["success"])
        released = inventory_process(self.inventory, payment["payment_event"], "payments.results")
        self.assertTrue(released["result"]["released"])
        replayed = inventory_process(self.inventory, payment["payment_event"], "payments.results")
        self.assertTrue(replayed["duplicate"])
        self.assertEqual(self.inventory.execute("SELECT stock, version FROM products WHERE product_id = %s", ("P01",)).fetchone(), {"stock": 10, "version": 2})
        return [row["payload"] for row in self.inventory.execute(
            "SELECT payload FROM outbox_events WHERE topic = %s ORDER BY id", ("inventory.updated",),
        ).fetchall()]

    def test_native_tv3_failure_flow_exposes_missing_version_contract(self):
        events = self.failed_payment_flow()
        self.assertEqual(len(events), 3)
        missing_version = [event for event in events if "version" not in event["data"]]
        if not missing_version:
            self.skipTest("TV3 now emits version; native versioned component test covers this flow")
        for payload in missing_version:
            with self.assertRaisesRegex(ValueError, "TV3 must publish"):
                process_event(self.admin, payload)
        self.assertEqual(self.processed_count(), 0)
        self.assertIsNone(self.stock())

    def test_native_versioned_reserve_payment_failure_release_projection(self):
        events = self.failed_payment_flow()
        if any("version" not in event["data"] for event in events):
            self.skipTest("TV3 StockUpdated outbox omits version; native Stock View integration requires TV3 contract fix")
        for payload in events:
            process_event(self.admin, payload)
        self.assertEqual(self.stock(), {"stock_after": 10, "version": 2})
        self.assertEqual([payload["data"]["version"] for payload in events], [0, 1, 2])

    def test_no_overselling_with_forced_success_and_concurrent_orders(self):
        from services.inventory.consumer import process_event as inventory_process
        from services.inventory.database import seed_product
        from services.order.producer import create_order
        from services.payment.consumer import process_event as payment_process
        from services.payment.settings import PaymentSettings

        seed_product(self.inventory, "P01", 5)

        def worker(index):
            order_id = f"component-success-{index}"
            with self.inventory_connection() as conn:
                result = inventory_process(conn, create_order("P01", 1, order_id), "orders.created")
                response = conn.execute(
                    "SELECT payload FROM outbox_events WHERE topic = %s AND message_key = %s",
                    ("inventory.results", order_id),
                ).fetchone()["payload"]
                payment = payment_process(AcknowledgingProducer(), response, PaymentSettings(mode="success"))
                if result["result"]["success"]:
                    self.assertTrue(payment["payment_event"]["data"]["success"])
                    inventory_process(conn, payment["payment_event"], "payments.results")
                else:
                    self.assertTrue(payment["skipped"])
                return result["result"]["success"]

        with ThreadPoolExecutor(max_workers=4) as pool:
            accepted = list(pool.map(worker, range(20)))
        self.assertEqual(sum(accepted), 5)
        self.assertEqual(len(accepted) - sum(accepted), 15)
        product = self.inventory.execute("SELECT stock, version FROM products WHERE product_id = %s", ("P01",)).fetchone()
        self.assertEqual(product, {"stock": 0, "version": 5})
        counts = self.inventory.execute("SELECT status, count(*) AS count FROM reservations GROUP BY status").fetchall()
        self.assertEqual({row["status"]: row["count"] for row in counts}, {"RESERVED": 5, "REJECTED": 15})


class AcknowledgingProducer:
    """Only the transport is fake; component DB transactions are real PostgreSQL."""

    def __init__(self):
        self.pending = []

    def produce(self, *, topic, key, value, callback):
        self.pending.append(callback)

    def poll(self, timeout):
        for callback in self.pending:
            callback(None, None)
        self.pending.clear()


